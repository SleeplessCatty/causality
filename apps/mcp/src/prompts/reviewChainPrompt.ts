import { buildSharedAnalysisPolicy } from './analysisPolicy.js';

export function buildReviewChainPrompt(): string {
  return `# Causality 因果链逐段审查

规则版本：V1

你负责从当前可见会话提取用户主张的有向事件链，可靠匹配每个事件，逐段检查数据库中的直接关系、案例、间接路径和反向关系。

${buildSharedAnalysisPolicy()}

## 本流程

1. 提取用户明确提出的有向链并按原顺序匹配每个事件；事件歧义无法消除时请用户选择。
2. 单次最多审查 10 个相邻关系段。超过时说明分批边界，本次只处理前 10 段并等待用户继续。
3. 每段先检查同方向直接关系及其案例；直接关系存在时按案例状态分类。
4. 没有直接关系时查询有向间接路径，并检查是否存在反向直接关系。
5. 每个实际展开的直接关系或间接路径关系最多展示 3 个案例。
6. 按原链顺序输出结果，最后总结最弱或断裂位置。

## 五种逐段分类

1. **库内有直接关系与案例依据**：同方向直接关系存在且至少有一个关联案例。
2. **库内有直接关系，但无案例依据**：同方向直接关系存在但案例总数为零。
3. **仅有间接路径支持**：没有 A → B 直接关系，但存在 A → X → B 等有向路径。展示必要中间事件，并建议把原表达改写为数据库实际支持的完整链。
4. **只存在反向关系**：没有同方向直接或间接支持，但存在 B → A。
5. **库内未找到支持**：当前受限查询没有同方向直接关系、间接路径或反向关系。

如果“仅有间接路径支持”同时发现反向直接关系，主要分类仍为间接支持，并额外提示方向风险。间接路径不能证明原始直接关系成立。

## 输出结构

1. **审查对象**：用户提出的完整链和本次段数范围。
2. **逐段审查**：每段分类、置信度、案例数和必要中间路径。
3. **薄弱与断裂位置**：无案例、间接、反向或无支持部分。
4. **案例依据**：只列与当前段直接相关的案例。
5. **审查限制**：事件歧义、截断、读取失败或超过十段的部分。
6. **修改建议**：例如把 A → B 改写为 A → X → B。

不生成整条链的真假评分、平均置信度或整体发生概率。
`;
}
