import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';

export const CAUSALITY_CAPTURE_PROMPT_NAME = 'causality_capture';

export function buildCausalityCapturePrompt(): string {
  return `# Causality 会话采集与入库

规则版本：V2

你负责把当前 AI 会话中与用户关心主线相关的内容，整理为 Causality 的原子事件、具体案例、因果关系和案例关联。AI 客户端内部使用 MCP 工具的 JSON 参数；向用户展示时使用清晰的普通语言。CSV 只属于应用的人工导入导出功能，本流程不得生成或解析 CSV。

## 启动和采集范围

1. 只有用户明确发起采集与入库指令时才能启动本流程。分析、追问和普通数据库查询不得自行触发采集。
2. 自动查找当前可见会话中最后一个成功标记 \`[Causality-Capture: <historyId>]\`：
   - 找到标记时，只采集该标记之后的可见对话；
   - 没有标记时，从当前可见会话最早内容开始；
   - 不得声称读取客户端未提供的隐藏历史。
3. 结合用户的问题和原因/结果追溯方向，只提取与用户问题和追溯主线直接相关的内容；排除背景闲谈、举例中的无关支线和无法支持主线的数据。
4. 一次最多 50 条原子事件。具体案例、因果关系和案例关联不另设业务条数上限，但都必须依赖这批原子事件并保持引用完整。

## 主线相关性

生成候选前，先在内部确定一个简短的主题锚点，判断用户正在追溯原因、结果还是双向链路，并限定当前可见会话中能够支持该主线的事实范围。

- 只采集位于主题锚点原因链或结果链上的内容；只提供背景说明、没有进入主线的事件和案例不采集。
- 每个准备新增或复用的原子事件至少是一个有效候选关系的端点；每个具体案例至少支持一个有效候选关系。
- 无法判断是否属于主线时采用保守策略，不扩展无关知识。

## 数据边界

- 原子性由当前讨论语境和知识建模目的决定：原子事件是在当前问题下不再需要继续拆分、能够精准作为因果关系端点的最小事件表达，不要求完全抽象化。
- 原子事件可以包含真实主体，例如“阿里巴巴美股股价上升”“特斯拉汽车销量下滑”；也可以包含改变因果含义所必需的限定语，例如“国内融资成本上升”。使用“主体或范围 + 单一状态、动作或变化方向”表达。
- 不要在名称中堆叠一次真实发生记录的时间、地点和过程细节；这些内容属于具体案例。说明只解释同一事件的边界，不得加入第二个事件。
- 如果一句表达包含两个可以分别成为因果端点的变化，例如“美联储提高政策利率并导致美国企业融资成本上升”，必须拆成两个原子事件并用因果关系连接。不要仅凭连接词机械拆分，要按语义判断。
- 具体案例是已经真实发生的一次事件记录，不是抽象规律、预测、假设或通用说明。在 100 字限制内保留能够区分该次记录的主体、已知时间或时间范围，以及必要地点或结果。
- 只使用当前可见会话已经提供或客户端已经核实的事实，不得编造缺失的日期、数字、地点、来源或时间间隔。同一真实发生记录的不同措辞视为复用候选；无法可靠判断是否为同一记录时选择 skip。
- 网页标题、URL、引用、事实摘要、时间和时间间隔只能帮助 AI 判断，不能作为额外业务类型入库；必要内容必须转化进三类业务数据。
- 已有原子事件名称不可修改，只能追加别名、关键词或替换说明；已有具体案例内容不可修改；已有因果关系端点和说明不可修改。
- 因果关系置信度由应用在案例关联变化时自动计算；AI 不直接给出或修改置信度。
- 不得使用通用新增、编辑、删除、合并或 SQL 能力绕过采集工具。

## 因果关系依据

- 因果关系必须有当前可见会话中的明确陈述、真实案例或清楚的机制说明作为依据。仅有时间先后、共同出现、相关性或常识上的可能性不足以建立关系。
- 信息只支持 \`A → B → C\` 时，只建立 \`A → B\` 和 \`B → C\`。只有存在独立依据证明 A 直接导致 C 时，才同时建立 \`A → C\`。
- 中间机制已经在会话事实中明确出现时，将其提取为原子事件；只怀疑存在中间机制但当前内容无法确认时，不得自行发明中间事件，应省略该关系，不得将其放入候选集合。
- 原因和结果方向必须与依据一致，原因和结果不得引用同一个原子事件。已有反向关系不是同一关系；只有两个方向分别有依据时才同时保留。

## 调用对比工具前的完整自检

调用 \`compare_knowledge_candidates\` 前，按以下顺序检查完整候选集合：

1. **范围**：采集区间、主题锚点和追溯方向正确。
2. **相关性**：没有脱离主线的事件或案例。
3. **原子性**：每个事件只表达一个状态、动作或变化。
4. **真实性**：每个具体案例都是当前内容中已经发生的事实。
5. **因果依据**：关系方向合理，没有用时间先后或想象代替依据。
6. **直接性**：已经提取当前内容明确给出的必要中间事件。
7. **批次去重**：事件、案例、同方向关系和案例关联在当前批次内各自唯一。
8. **引用完整**：关系端点引用本批次事件 ref，案例关联引用本批次关系和案例 ref。
9. **无孤立候选**：有效事件进入至少一条有效关系，有效案例进入至少一条有效案例关联。
10. **数量和字段**：去重后事件不超过 50 条，所有字段符合工具发布的 Schema。

质量不合格且无法修复的内容不进入候选集合。内容本身有效、但无法判断应该新增还是复用时，才在方案决策中选择 skip。

## 严格 JSON 调用

- 严格使用 MCP 工具实时发布的 JSON Schema，不复制或猜测字段。直接发送工具参数对象，不把 JSON 包装成 Markdown、字符串或 CSV。
- 一次提交包含原子事件、具体案例、因果关系和案例关联四类完整候选数组，不拆成多次局部对比。
- 原子事件始终显式提供 \`aliases\` 和 \`keywords\` 数组，无内容时使用空数组；可空说明没有可靠内容时使用 null，不编造占位文字。
- 使用批次内稳定、唯一且可读的 ref，推荐 \`event-001\`、\`case-001\`、\`relation-001\`。ref 不是数据库 ID，在同一次对比、方案生成和修改循环中不得无故变化。
- 关系只引用事件 ref，案例关联只引用关系 ref 和案例 ref。对比结果必须原样随候选集合交给方案生成工具，不得伪造、删改或手工重算。
- 决策必须覆盖完整候选集合；依赖项被 skip 时，其关系或案例关联也必须同步 skip。修改后重新提交完整候选、对比和决策集合，不提交差异补丁。

## 库内对比决策

- 原子事件的名称、别名和语义候选只是判断依据，不自动等于同一事件。主体、范围、状态、方向和粒度一致时优先复用；主体、范围、状态或动作、变化方向或有效粒度不同并改变因果含义时新增；无法可靠区分时 skip。
- 复用原子事件时只能追加别名、追加关键词或替换说明；替换说明必须更准确地描述同一事件边界，替换说明不能改变已有事件含义。
- 具体案例综合比较主体、发生时间、动作和结果：明确是同一次真实发生记录时复用；明确是另一时间、主体、动作或结果的发生记录时新增；只有主题相似但不能确认时 skip。
- 相同原因端点、结果端点和方向的已有关系复用；反向关系不当作同一关系。已有关联复用，不重复创建。

## 服务端质量报告与自动修复

- \`compare_knowledge_candidates\` 返回的服务端质量报告优先于 AI 自检结论。读取 \`qualityReport.status\`、\`issues\`、\`paths\`、\`refs\`、\`aiCanRepair\` 和 \`suggestedAction\`，不得用 AI 自己的判断覆盖报告。
- 报告状态为 blocked 时，不得生成或展示首次方案，也不得要求用户判断或协助修复。必须依据报告的路径和 ref 修正同一完整工作集；合并、拆分或移除候选后，必须重写工作集中所有受影响的关系端点、案例关联和其他引用。无法修复的内容移入忽略数据，并保留其忽略原因；随后必须重新提交完整候选集合并重新执行完整对比，直到不再 blocked。
- 报告状态为 warning 时，结合当前可见会话事实和报告内容判断；受影响内容默认归入存疑数据并使用 skip。可以在事实足以可靠支持时作出其他合规决策，但只有不存在 blocked 后才继续生成方案。
- \`topicRelevance\` 只用于同一批次事件相对于主题锚点的相关性复核；不得设置固定阈值，不得根据 topicRelevance 单独建立或否定因果关系，不得因单一低分自动删除真实主体或限定语不同的事件。
- 系统或配置错误不得通过改写业务数据规避；停止自动循环，向用户说明需要人工处理并等待处理结果。

## 自动分类与方案展示

首次完整方案生成之前，所有提取、检查、对比和决策都由 AI 自动完成，不得要求用户逐项判断。将全部提取结果分为三类：

- **确信数据**：通过质量自检，并且 AI 能够可靠决定新增或复用；默认采用 create 或 reuse，是用户确认方案后实际提交的写入集合。
- **存疑数据**：与主线相关且结构有效，但 AI 无法可靠判断新增或复用，或仍需用户确认边界；默认采用 skip，说明疑点和建议。能够满足工具 Schema 时纳入候选和方案决策。
- **忽略数据**：与主线无关、依据不足、批次内重复或无法形成有效业务数据；不进入候选写入集合，但必须在用户可读方案中列出内容和忽略原因。

用户可读方案必须按三类分组，并在每类下按原子事件、具体案例、因果关系和案例关联展示可读内容、AI 决策及原因。忽略数据只保留在当前会话的方案说明中，不伪装为服务端已保存的数据。用户直接确认时，只提交确信数据；存疑和忽略数据保持不入库。

## 自动生成方案

从用户发起采集到首次生成入库方案，以下步骤自动连续执行，不逐步询问用户：

1. 提取完整工作集，完成质量自检和三类自动分类；为进入候选集合的原子事件、具体案例和因果关系分配本批次内稳定且唯一的 \`ref\`，案例关联只使用 \`relationRef\` 和 \`caseRef\`。
2. 调用 \`compare_knowledge_candidates\`，一次提交确信数据和结构有效的存疑数据所组成的四类完整候选数组。
3. 按“服务端质量报告与自动修复”处理报告：blocked 时自动修复同一完整工作集、重写全部引用并重新对比；warning 时按会话事实处理并默认将受影响内容归入存疑数据和 skip。这个循环中不得询问用户；只有不再 blocked 才进入下一步。
4. 按“库内对比决策”综合判断普通匹配、语义匹配和关系端点；无法可靠判断时必须选择 skip，不得以猜测替代判断。
5. 只有不再 blocked 后，才调用 \`prepare_knowledge_changes\` 生成不可变、限时有效的服务端方案，再合并当前工作集中的忽略数据，用普通语言展示完整的三类方案、主题和采集范围；按原子事件、具体案例、因果关系和案例关联分别列出，并说明原子事件补充内容和预期自动置信度变化。然后询问用户是修改方案还是确认最新方案。

## 方案修改与确认

- 用户可以对方案提出修改建议。每次修改都重新自检受影响候选，完成必要的库内对比，再生成一份替代旧方案的完整方案，不能只展示差异补丁。
- 修改循环可以持续多轮。只有用户明确确认最新完整方案后，才可调用 \`commit_knowledge_changes\`。
- 提交前使用 \`get_import_plan_status\` 确认方案仍可提交。提交参数只能包含最新方案 ID。
- 用户的“开始采集”“继续”“看起来可以”等含糊表达不构成入库确认；确认必须明确指向最新完整方案。

## 失败和完成

- MCP Schema 解析失败时，根据字段路径修正完整参数对象后重试同一步骤，不拆分或绕过工具调用。
- 数据错误：依据错误中的 \`affectedRefs\`、\`aiCanRepair\` 和建议动作修正候选或决策，重新对比并重新生成完整方案，再次请用户确认；不得自动提交修订方案。
- 不通过改写业务数据规避系统或配置错误。系统错误中当前方案可重试时，只向用户说明原因并停止并等待用户决定重试；不可重试时提示需要人工处理。
- 提交响应不明确时，使用 \`get_import_plan_status\` 或 \`get_import_result\` 查询，避免重复生成或重复提交。
- 不得在工具失败、响应不明或方案失效时宣称入库成功。
- 成功后向用户说明实际入库结果，并逐字输出服务端返回的成功标记，格式为 \`[Causality-Capture: <historyId>]\`。该标记是下次自动确定采集范围的边界。
`;
}

export function registerCapturePrompt(server: McpServer): void {
  server.registerPrompt(
    CAUSALITY_CAPTURE_PROMPT_NAME,
    {
      title: '采集当前会话并生成入库方案',
      description: '按受控流程从当前可见会话提取因果知识、对比数据库并等待用户确认入库。',
    },
    async () => ({
      description: 'Causality 会话采集与入库流程',
      messages: [
        {
          role: 'user',
          content: {
            type: 'text',
            text: buildCausalityCapturePrompt(),
          },
        },
      ],
    }),
  );
}
