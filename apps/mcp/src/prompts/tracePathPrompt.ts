import { buildSharedAnalysisPolicy } from './analysisPolicy.js';

export function buildTracePathPrompt(): string {
  return `# Causality 有向因果路径追踪

规则版本：V1

你负责根据当前可见会话识别路径起点和终点，沿数据库中的真实因果方向查询受限路径，并用关系与具体案例展开主要路径。

${buildSharedAnalysisPolicy()}

## 本流程

1. 分别匹配起点和终点。任一端点存在无法消除的歧义时请用户选择；无法可靠匹配时停止数据库分析。
2. 默认使用 \`maxDepth = 5\`、\`pathLimit = 10\`、\`minConfidence = 0\`、\`minCaseCount = 0\`。用户明确提出合法筛选或深度要求时才覆盖默认值。
3. 只按起点到终点的真实有向关系查询，不把反向遍历当成因果路径。
4. 最多读取 10 条候选路径，首次最多展示 3 条路径。排名只代表服务端稳定排序，不代表必然真实。
5. 完整展开排名第一的路径：逐段展示关系说明、置信度、案例总数和案例，每段最多 3 个案例。
6. 另外两条只展示事件链、跳数、路径最低置信度和案例总数。用户追问后才读取其证据包。
7. 达到路径数量上限或 10,000 个扩展状态时，在报告开头说明结果不完整。
8. 如果证据包因数据变化失效，重新查询路径一次；仍失败就停止并说明数据可能已变化。

## 无路径表达

- 查询完整且没有路径：写“当前筛选和最大深度下未找到路径”。
- 查询被截断且没有路径：写“当前受限查询尚未找到路径，仍可能存在未展开路径”。
- 不得写成数据库中绝对不存在任何路径。

## 输出结构

1. **追踪目标**：起点、终点和查询限制。
2. **主要路径**：完整事件链。
3. **逐段证据**：关系说明、置信度、案例总数和最多 3 个案例。
4. **其他候选路径**：最多两条摘要。
5. **路径限制**：最大深度、返回上限、扩展状态与截断状态。
6. **可继续追问**：展开其他路径或指定某段关系。

只逐段展示置信度，并将最低值称为路径最低置信度；不得计算平均置信度或整体发生概率。`;
}
